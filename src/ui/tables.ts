// The renderer's lookup tables. They depend on nothing that varies per page
// and take a few seconds, so the build computes them once (scripts/tables.js)
// into tables.data.js, which the renderer loads.
//
//   rgb        TABLE_ROWS × 256 RGB triples: row k is nicrainha's 256-gon,
//              in vertex order, at L* 100 · k / (TABLE_ROWS − 1). Every
//              lightness shares the same 256 hue angles, so a vertex keeps
//              its hue from row to row.
//   sizes      each row's palette (palette.ts): its size n,
//   rotations  and its rotation.
//   cdf        the noise's value distribution (noise.ts).

import { generatePalettes } from "../colors.js";
import { TABLE_ROWS as ROWS } from "./model.js";
import { perlinCdf } from "./noise.js";
import { largestPalette } from "./palette.js";

export interface Tables {
	rgb: Uint8Array;
	sizes: number[];
	rotations: number[];
	cdf: number[];
}

export function buildTables(): Tables {
	const rgb = new Uint8Array(ROWS * 256 * 3);
	const sizes: number[] = [];
	const rotations: number[] = [];
	for (let row = 0; row < ROWS; row++) {
		const ring = generatePalettes(256, { lightness: (100 * row) / (ROWS - 1) })[0];
		ring.forEach(({ r, g, b }, vertex) => rgb.set([r, g, b], (row * 256 + vertex) * 3));
		const { size, rotation } = largestPalette(ring);
		sizes.push(size);
		rotations.push(rotation);
	}
	return { rgb, sizes, rotations, cdf: perlinCdf() };
}

// The tables as the source of an ES module.
export function tablesModule({ rgb, sizes, rotations, cdf }: Tables): string {
	return [
		"// Generated by scripts/tables.js from src/ui/tables.ts. Do not edit.",
		`export const RGB = "${Buffer.from(rgb).toString("base64")}";`,
		`export const SIZES = ${JSON.stringify(sizes)};`,
		`export const ROTATIONS = ${JSON.stringify(rotations)};`,
		`export const CDF = ${JSON.stringify(cdf.map((c) => +c.toFixed(6)))};`,
		"",
	].join("\n");
}
